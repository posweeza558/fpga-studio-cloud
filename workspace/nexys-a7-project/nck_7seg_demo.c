// ==============================================================================
// FPGA Studio — การคำนวณ n C k (10 C 3 = 120) ภาษา C แบบมาตรฐาน (Standard C)
// รันบน CPU RISC-V RV32IM พร้อมวงจรฮาร์ดแวร์คูณ-หารแท้ (Hardware MUL / DIV) บนบอร์ด Nexys A7
// ไม่ใช้ฟังก์ชันจำลองบวกลบเลื่อนบิต — ใช้โอเปอเรเตอร์ *, /, % โดยตรง 100%
// ==============================================================================

#define LED     (*(volatile int*)0xF0000000) // ไฟ LED 16 ดวง (Binary)
#define SEG7    (*(volatile int*)0xF0000008) // 7-Segment Display 8 หลัก (Hex/BCD)

// ฟังก์ชันแปลงเลขฐานสิบเป็น BCD 4 หลัก โดยใช้เครื่องหมายหาร (/) และเศษ (%) ปกติ
static int to_bcd4(int val) {
    int bcd = 0;
    int shift = 0;
    while (val > 0 && shift < 16) {
        bcd |= (val % 10) << shift;
        val = val / 10;
        shift += 4;
    }
    return bcd;
}

// รวมค่าตัวแปร n, k และผลลัพธ์ ans ออกเป็นรูปแบบหน้าจอ 7-Segment 8 หลัก:
// [n: 2 หลัก BCD] [ 'C' ] [k: 1 หลัก] [ans: 4 หลัก BCD]
static int pack_7seg(int n, int k, int ans) {
    int n_bcd = ((n / 10) << 4) | (n % 10);
    return (n_bcd << 24) | (0xC << 20) | ((k & 0xF) << 16) | (to_bcd4(ans) & 0xFFFF);
}

// ฟังก์ชันคำนวณ n C k แบบทั่วไป ด้วยสูตรมาตรฐาน ans = (ans * (n - i + 1)) / i
int n_choose_k(int n, int k) {
    if (k < 0 || k > n) return 0;
    if (k == 0 || k == n) return 1;
    if (k > n - k) k = n - k; // สมมาตร nCk = nC(n-k) เพื่อลดจำนวนรอบคูณ
    
    int ans = 1;
    for (int i = 1; i <= k; i++) {
        ans = (ans * (n - i + 1)) / i; // ใช้ Hardware Multiplier & Divider ตรงๆ
    }
    return ans;
}

int main(void) {
    int n = 10;
    int k = 3;
    __asm__ __volatile__("" : "+r"(n), "+r"(k));

    // --------------------------------------------------------------------------
    // ขั้นที่ 1: กำหนด n = 10
    // • ไฟ LED: 10 (0b0000_0000_0000_1010)
    // • 7-Segment: แสดง "10 C 0 0000" (บอกค่า n = 10)
    // --------------------------------------------------------------------------
    LED = n;
    SEG7 = pack_7seg(n, 0, 0);

    // --------------------------------------------------------------------------
    // ขั้นที่ 2: กำหนด k = 3
    // • ไฟ LED: 3 (0b0000_0000_0000_0011)
    // • 7-Segment: แสดง "10 C 3 0000" (แสดงโจทย์ 10 C 3)
    // --------------------------------------------------------------------------
    LED = k;
    SEG7 = pack_7seg(n, k, 0);

    // --------------------------------------------------------------------------
    // ขั้นที่ 3: คำนวณรอบที่ 1 -> 10 C 1 = 10
    // • ans = 10
    // • ไฟ LED: 10
    // • 7-Segment: แสดง "10 C 1 0010"
    // --------------------------------------------------------------------------
    int ans = n;
    __asm__ __volatile__("" : "+r"(ans));
    LED = ans;
    SEG7 = pack_7seg(n, 1, ans);

    // --------------------------------------------------------------------------
    // ขั้นที่ 4: คำนวณรอบที่ 2 -> 10 C 2 = (ans * 9) / 2 = 45
    // • ans = 45
    // • ไฟ LED: 45 (0b0000_0000_0010_1101)
    // • 7-Segment: แสดง "10 C 2 0045"
    // คำนวณผ่าน Hardware MUL และ DIV บน FPGA โดยตรง
    // --------------------------------------------------------------------------
    ans = (ans * (n - 1)) / 2;
    __asm__ __volatile__("" : "+r"(ans));
    LED = ans;
    SEG7 = pack_7seg(n, 2, ans);

    // --------------------------------------------------------------------------
    // ขั้นที่ 5: คำนวณรอบที่ 3 -> 10 C 3 = (45 * 8) / 3 = 120 (คำตอบสุดท้าย!)
    // • ans = 120
    // • ไฟ LED: 120 (0b0000_0000_0111_1000)
    // • 7-Segment: แสดง "10 C 3 0120"
    // คำนวณผ่าน Hardware MUL และ DIV บน FPGA โดยตรง
    // --------------------------------------------------------------------------
    ans = (ans * (n - 2)) / 3;
    __asm__ __volatile__("" : "+r"(ans));
    LED = ans;
    SEG7 = pack_7seg(n, 3, ans);

    // ค้างผลลัพธ์สุดท้ายไว้บนหน้าจอ
    while (1) {
    }

    return 0;
}
