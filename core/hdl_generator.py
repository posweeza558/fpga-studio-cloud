def generate_nexys_a7_soc_top_verilog(cpu_module_name="openmips", mmio_map=None, binding=None):
    """Generate complete Nexys A7-100T SoC top-level Verilog wrapper."""
    mmio = mmio_map or {}
    led_addr  = int(str(mmio.get("led",       "0xF0000000")), 16)
    sw_addr   = int(str(mmio.get("sw",        "0xF0000004")), 16)
    seg7_addr = int(str(mmio.get("seg7",      "0xF0000008")), 16)
    btn_addr  = int(str(mmio.get("btn",       "0xF000000C")), 16)
    uart_addr = int(str(mmio.get("uart_tx",   "0xF0000010")), 16)
    stat_addr = int(str(mmio.get("uart_stat", "0xF0000014")), 16)
    rgb_addr  = int(str(mmio.get("rgb",       "0xF0000018")), 16)

    if binding and binding.get("ok"):
        from core.cpu_port_binding import render_cpu_instance
        cpu_module_name = binding["module"]
        cpu_inst_block = render_cpu_instance(
            binding,
            "u_cpu",
            {
                "clk": "sys_clk", "rst": "cpu_rst",
                "rom_addr": "rom_addr", "rom_data": "rom_data", "rom_ce": "rom_ce",
                "ram_addr": "ram_addr", "ram_wdata": "ram_wdata", "ram_rdata": "ram_rdata",
                "ram_we": "ram_we", "ram_ce": "ram_ce", "ram_sel": "ram_sel",
            },
        )
    else:
        cpu_inst_block = f"""    {cpu_module_name} u_cpu (
        .clk        (sys_clk),
        .rst        (cpu_rst),
        .rom_addr_o (rom_addr),
        .rom_data_i (rom_data),
        .rom_ce_o   (rom_ce),
        .ram_addr_o (ram_addr),
        .ram_data_o (ram_wdata),
        .ram_data_i (ram_rdata),
        .ram_we_o   (ram_we),
        .ram_ce_o   (ram_ce),
        .ram_sel_o  (ram_sel)
    );"""

    return f"""// ==============================================================================
// FPGA Studio — Digilent Nexys A7-100T SoC Top Module ({cpu_module_name})
// Connects CPU Core + Reprogrammable 16KB IMEM + 16KB Byte-Lane DMEM + MMIO + UART
// ==============================================================================
module nexys_a7_soc_top (
    input  wire        CLK100MHZ,
    input  wire        CPU_RESETN,
    input  wire [15:0] SW,
    output reg  [15:0] LED,
    output reg  [6:0]  SEG_CA,
    output wire        SEG_DP,
    output reg  [7:0]  SEG_AN,
    input  wire        BTNC,
    input  wire        BTNU,
    input  wire        BTNL,
    input  wire        BTNR,
    input  wire        BTND,
    output wire        LED16_R,
    output wire        LED16_G,
    output wire        LED16_B,
    output wire        LED17_R,
    output wire        LED17_G,
    output wire        LED17_B,
    input  wire        UART_TXD_IN,
    output reg         UART_RXD_OUT
);

    // 1. 25 MHz CPU System Clock Divider (ensures clean Artix-7 timing closure)
    reg [1:0] clk_div = 2'd0;
    always @(posedge CLK100MHZ) clk_div <= clk_div + 2'd1;
    wire sys_clk = clk_div[1]; // 25 MHz
    wire ext_rst = ~CPU_RESETN;

    // 2. USB-UART Live Program Loader ("PROG" & "DMEM" protocol @ 115200 baud)
    wire        prog_busy;
    wire        prog_we;
    wire        prog_dmem_we;
    wire [11:0] prog_addr;
    wire [31:0] prog_wdata;
    wire        rx_valid;
    wire [7:0]  rx_byte;

    uart_prog_loader #(
        .CLKS_PER_BIT(217)
    ) u_loader (
        .clk             (sys_clk),
        .rst             (ext_rst),
        .uart_rx_i       (UART_TXD_IN),
        .prog_busy_o     (prog_busy),
        .prog_we_o       (prog_we),
        .prog_dmem_we_o  (prog_dmem_we),
        .prog_addr_o     (prog_addr),
        .prog_wdata_o    (prog_wdata),
        .rx_byte_valid_o (rx_valid),
        .rx_byte_data_o  (rx_byte)
    );

    wire cpu_rst = ext_rst | prog_busy;

    // 3. Reprogrammable 4096-word (16 KB) Instruction Memory
    (* ram_style = "distributed" *) reg [31:0] imem [0:4095];
    initial begin
        $readmemh("program.hex", imem);
    end

    wire [31:0] rom_addr;
    wire        rom_ce;
    wire [31:0] rom_data = rom_ce ? imem[rom_addr[13:2]] : 32'd0;

    always @(posedge sys_clk) begin
        if (prog_we)
            imem[prog_addr] <= prog_wdata;
    end

    // 4. CPU Core Instantiation ({cpu_module_name})
    wire [31:0] ram_addr;
    wire [31:0] ram_wdata;
    reg  [31:0] ram_rdata;
    wire        ram_we;
    wire        ram_ce;
    wire [3:0]  ram_sel;

{cpu_inst_block}

    // 5. 4096-word (16 KB) Byte-Lane Data Memory
    (* ram_style = "distributed" *) reg [31:0] dmem [0:4095];
    initial begin
        $readmemh("dmem_init.hex", dmem);
    end

    wire is_mmio = (ram_addr[31:24] == 8'hF0) || (ram_addr[31:24] == 8'hFF);
    wire dmem_we = ram_ce && ram_we && !is_mmio;
    wire [11:0] dmem_idx = ram_addr[13:2];

    always @(posedge sys_clk) begin
        if (prog_dmem_we) begin
            dmem[prog_addr] <= prog_wdata;
        end else if (dmem_we) begin
            if (ram_sel[0]) dmem[dmem_idx][7:0]   <= ram_wdata[7:0];
            if (ram_sel[1]) dmem[dmem_idx][15:8]  <= ram_wdata[15:8];
            if (ram_sel[2]) dmem[dmem_idx][23:16] <= ram_wdata[23:16];
            if (ram_sel[3]) dmem[dmem_idx][31:24] <= ram_wdata[31:24];
        end
    end

    // 6. MMIO Peripherals & 115200-baud UART TX
    reg [31:0] seg7_reg;
    reg [23:0] rgb_reg;
    reg [7:0]  rx_latched;
    reg        rx_has_byte;

    // UART Transmitter (25 MHz / 217 = 115200 baud)
    reg [3:0]  tx_bit_idx;
    reg [15:0] tx_clk_cnt;
    reg [9:0]  tx_frame;
    reg        tx_busy;

    wire [5:0] btn_bus = {{ext_rst, BTND, BTNR, BTNL, BTNU, BTNC}};

    always @(posedge sys_clk or posedge cpu_rst) begin
        if (cpu_rst) begin
            LED          <= 16'd0;
            seg7_reg     <= 32'd0;
            rgb_reg      <= 24'd0;
            rx_latched   <= 8'd0;
            rx_has_byte  <= 1'b0;
            UART_RXD_OUT <= 1'b1;
            tx_busy      <= 1'b0;
            tx_clk_cnt   <= 16'd0;
            tx_bit_idx   <= 4'd0;
            tx_frame     <= 10'h3FF;
        end else begin
            if (rx_valid) begin
                rx_latched  <= rx_byte;
                rx_has_byte <= 1'b1;
            end

            // UART TX shifting
            if (tx_busy) begin
                UART_RXD_OUT <= tx_frame[0];
                if (tx_clk_cnt == 16'd216) begin
                    tx_clk_cnt <= 16'd0;
                    tx_frame   <= {{1'b1, tx_frame[9:1]}};
                    if (tx_bit_idx == 4'd9)
                        tx_busy <= 1'b0;
                    else
                        tx_bit_idx <= tx_bit_idx + 4'd1;
                end else begin
                    tx_clk_cnt <= tx_clk_cnt + 16'd1;
                end
            end else begin
                UART_RXD_OUT <= 1'b1;
            end

            // MMIO Writes
            if (ram_ce && ram_we) begin
                case (ram_addr)
                    32'h{led_addr:08X}:  LED      <= ram_wdata[15:0];
                    32'h{seg7_addr:08X}: seg7_reg <= ram_wdata;
                    32'h{rgb_addr:08X}:  rgb_reg  <= ram_wdata[23:0];
                    32'h{uart_addr:08X}: begin
                        if (!tx_busy) begin
                            tx_frame   <= {{1'b1, ram_wdata[7:0], 1'b0}};
                            tx_busy    <= 1'b1;
                            tx_clk_cnt <= 16'd0;
                            tx_bit_idx <= 4'd0;
                        end
                    end
                    default: ;
                endcase
            end

            // Clear UART RX ready flag on read
            if (ram_ce && !ram_we && ram_addr == 32'h{uart_addr:08X})
                rx_has_byte <= 1'b0;
        end
    end

    // MMIO & Data Memory Read Mux
    always @(*) begin
        if (!ram_ce) begin
            ram_rdata = 32'd0;
        end else if (is_mmio) begin
            case (ram_addr)
                32'h{led_addr:08X}:  ram_rdata = {{16'd0, LED}};
                32'h{sw_addr:08X}:   ram_rdata = {{16'd0, SW}};
                32'h{seg7_addr:08X}: ram_rdata = seg7_reg;
                32'h{btn_addr:08X}:  ram_rdata = {{26'd0, btn_bus}};
                32'h{uart_addr:08X}: ram_rdata = {{24'd0, rx_latched}};
                32'h{stat_addr:08X}: ram_rdata = {{30'd0, ~tx_busy, rx_has_byte}};
                32'h{rgb_addr:08X}:  ram_rdata = {{8'd0, rgb_reg}};
                default:             ram_rdata = 32'd0;
            endcase
        end else begin
            ram_rdata = dmem[dmem_idx];
        end
    end

    // 7. 8-Digit Multiplexed 7-Segment Display Driver
    assign SEG_DP = 1'b1;
    reg [16:0] scan_cnt = 17'd0;
    always @(posedge sys_clk) scan_cnt <= scan_cnt + 17'd1;
    wire [2:0] digit_sel = scan_cnt[16:14];
    wire [3:0] nibble = seg7_reg[digit_sel * 4 +: 4];

    always @(*) begin
        SEG_AN = ~(8'b0000_0001 << digit_sel);
        case (nibble)
            4'h0: SEG_CA = 7'b1000000;
            4'h1: SEG_CA = 7'b1111001;
            4'h2: SEG_CA = 7'b0100100;
            4'h3: SEG_CA = 7'b0110000;
            4'h4: SEG_CA = 7'b0011001;
            4'h5: SEG_CA = 7'b0010010;
            4'h6: SEG_CA = 7'b0000010;
            4'h7: SEG_CA = 7'b1111000;
            4'h8: SEG_CA = 7'b0000000;
            4'h9: SEG_CA = 7'b0010000;
            4'hA: SEG_CA = 7'b0001000;
            4'hB: SEG_CA = 7'b0000011;
            4'hC: SEG_CA = 7'b1000110;
            4'hD: SEG_CA = 7'b0100001;
            4'hE: SEG_CA = 7'b0000110;
            4'hF: SEG_CA = 7'b0001110;
        endcase
    end

    // 8. PWM Driver for RGB LEDs (LD16, LD17 — 25% max duty cycle per Digilent spec)
    reg [9:0] pwm_cnt = 10'd0;
    always @(posedge sys_clk) pwm_cnt <= pwm_cnt + 10'd1;
    assign LED16_R = (pwm_cnt < {{2'b00, rgb_reg[23:20], 4'd0}});
    assign LED16_G = (pwm_cnt < {{2'b00, rgb_reg[19:16], 4'd0}});
    assign LED16_B = (pwm_cnt < {{2'b00, rgb_reg[15:12], 4'd0}});
    assign LED17_R = (pwm_cnt < {{2'b00, rgb_reg[11:8],  4'd0}});
    assign LED17_G = (pwm_cnt < {{2'b00, rgb_reg[7:4],   4'd0}});
    assign LED17_B = (pwm_cnt < {{2'b00, rgb_reg[3:0],   4'd0}});

endmodule
"""


def export_vivado_soc_package(out_dir, instructions, arch="mips", cpu_hdl_path=None, mmio_map=None):
    """
    Export a complete, self-contained Xilinx Vivado Nexys A7-100T SoC Synthesis folder.
    Returns dict with paths of generated files.
    """
    os.makedirs(out_dir, exist_ok=True)
    rtl_cpu_dir = os.path.join(out_dir, "rtl_cpu")
    os.makedirs(rtl_cpu_dir, exist_ok=True)

    # 1. Copy synthesizable CPU RTL files & resolve port binding
    from core.cpu_port_binding import resolve_cpu_port_binding
    binding = resolve_cpu_port_binding(cpu_hdl_path, arch=arch)
    copied_rtl = []
    cpu_mod_name = binding["module"] if binding.get("ok") else ("openmips" if arch == "mips" else "riscv_rv32i")
    app_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    if cpu_hdl_path and os.path.exists(cpu_hdl_path):
        src_dir = os.path.dirname(os.path.abspath(cpu_hdl_path))
    else:
        core_sub = "openmips" if arch == "mips" else "riscv"
        src_dir = os.path.join(app_root, "custom_cpus", core_sub)

    if os.path.isdir(src_dir):
        skip_sim_wrappers = {"top.v", "inst_rom.v", "data_ram.v", "openmips_min_sopc.v", "openmips_min_sopc_tb.v"}
        for fn in sorted(os.listdir(src_dir)):
            if fn.lower() in skip_sim_wrappers or fn.lower().startswith("tb_"):
                continue
            if fn.lower().endswith((".v", ".sv", ".vh", ".vhd", ".vhdl")):
                shutil.copy2(os.path.join(src_dir, fn), os.path.join(rtl_cpu_dir, fn))
                copied_rtl.append(fn)

    # 2. Write program.hex (4096 words padded) & program.coe & dmem_init.hex
    imem_words = [0] * 4096
    init_dmem = {}
    if instructions:
        init_dmem = instructions[0].get("init_dmem", {}) or {}
        for idx, ins in enumerate(instructions[:4096]):
            imem_words[idx] = ins.get("word", int(ins["hex"], 16)) & 0xFFFFFFFF

    prog_hex_path = os.path.join(out_dir, "program.hex")
    with open(prog_hex_path, "w", encoding="utf-8") as f:
        f.write("\n".join(f"{w:08X}" for w in imem_words) + "\n")

    dmem_words = [0] * 4096
    for byte_addr, w_val in init_dmem.items():
        w_idx = ((int(byte_addr) & 0x00003FFF) >> 2)
        if 0 <= w_idx < 4096:
            dmem_words[w_idx] = int(w_val) & 0xFFFFFFFF

    dmem_hex_path = os.path.join(out_dir, "dmem_init.hex")
    with open(dmem_hex_path, "w", encoding="utf-8") as f:
        f.write("\n".join(f"{w:08X}" for w in dmem_words) + "\n")

    coe_path = os.path.join(out_dir, "program.coe")
    with open(coe_path, "w", encoding="utf-8") as f:
        f.write(generate_coe_content(instructions))

    # 3. Write uart_prog_loader.v, nexys_a7_soc_top.v, and Nexys-A7-100T-Master.xdc
    loader_path = os.path.join(out_dir, "uart_prog_loader.v")
    with open(loader_path, "w", encoding="utf-8") as f:
        f.write(generate_uart_prog_loader_verilog())

    top_path = os.path.join(out_dir, "nexys_a7_soc_top.v")
    with open(top_path, "w", encoding="utf-8") as f:
        f.write(generate_nexys_a7_soc_top_verilog(cpu_module_name=cpu_mod_name, mmio_map=mmio_map, binding=binding))

    xdc_path = os.path.join(out_dir, "Nexys-A7-100T-Master.xdc")
    with open(xdc_path, "w", encoding="utf-8") as f:
        f.write(generate_nexys_a7_xdc())

    # 4. Write Xilinx Vivado Tcl project builder script
    tcl_path = os.path.join(out_dir, "build_vivado_project.tcl")
    tcl_content = f"""# ==============================================================================
# FPGA Studio — Automated Xilinx Vivado Project & Bitstream Script
# Target FPGA: Digilent Nexys A7-100T (xc7a100tcsg324-1)
# Usage in Vivado Tcl Console:
#   cd {{{out_dir.replace(os.sep, '/')}}}
#   source build_vivado_project.tcl
# ==============================================================================
set proj_name "fpga_studio_nexys_a7"
create_project -force $proj_name ./vivado_proj -part xc7a100tcsg324-1

add_files -norecurse [glob -nocomplain ./rtl_cpu/*.v]
add_files -norecurse ./uart_prog_loader.v
add_files -norecurse ./nexys_a7_soc_top.v
add_files -norecurse ./program.hex
add_files -norecurse ./dmem_init.hex
add_files -fileset constrs_1 -norecurse ./Nexys-A7-100T-Master.xdc

set_property include_dirs [list ./rtl_cpu] [current_fileset]
set_property verilog_define [list SYNTHESIS=1] [current_fileset]
set_property top nexys_a7_soc_top [current_fileset]
update_compile_order -fileset sources_1

puts "=================================================================="
puts "Vivado project '$proj_name' created! Run 'launch_runs impl_1 -to_step write_bitstream' to build bitstream."
puts "=================================================================="
"""
    with open(tcl_path, "w", encoding="utf-8") as f:
        f.write(tcl_content)

    # 5. Write Thai Quickstart Guide
    readme_path = os.path.join(out_dir, "README_VIVADO_TH.md")
    readme_content = f"""# ชุดสังเคราะห์ฮาร์ดแวร์ FPGA Studio สำหรับบอร์ด Digilent Nexys A7-100T

แกนประมวลผลที่ส่งออก: **`{cpu_mod_name}`** ({arch.upper()})  
จำนวนคำสั่งเริ่มต้นใน ROM: **{len(instructions)} คำสั่ง (32-bit)**

## ไฟล์ในแพ็กเกจนี้
1. `nexys_a7_soc_top.v` — วงจรระดับบนสุด (SoC Top) เชื่อมต่อ CPU, หน่วยความจำ 16KB, สะพาน MMIO, 7-Segment 8 หลัก และ UART 115200
2. `uart_prog_loader.v` — วงจร Bootloader รับโปรแกรมใหม่ผ่านสาย USB-UART (`PROG` protocol) โดยไม่ต้องสังเคราะห์ Bitstream ซ้ำ!
3. `Nexys-A7-100T-Master.xdc` — ไฟล์กำหนดขาพินมาตรฐานของบอร์ด Nexys A7-100T (`xc7a100tcsg324-1`)
4. `rtl_cpu/` — ซอร์สโค้ด Verilog ของ CPU ({len(copied_rtl)} ไฟล์)
5. `program.hex` / `dmem_init.hex` / `program.coe` — ข้อมูลโปรแกรมเริ่มต้นสำหรับ Block/Distributed RAM
6. `build_vivado_project.tcl` — สคริปต์สร้างโปรเจกต์ Vivado อัตโนมัติ

## วิธีนำไปใช้งานบนบอร์ดจริง
1. เปิดโปรแกรม **Xilinx Vivado** แล้วเปิดแถบ **Tcl Console** ด้านล่าง
2. พิมพ์คำสั่ง:
   ```tcl
   cd {{{out_dir.replace(os.sep, '/')}}}
   source build_vivado_project.tcl
   ```
3. กด **Generate Bitstream** แล้ว **Program Device** ลงบอร์ด Nexys A7-100T เพียงครั้งเดียว
4. หลังจากโปรแกรม Bitstream นี้ลงบอร์ดแล้ว คุณสามารถแก้ไขโค้ด C / Assembly ใน **FPGA Studio** แล้วกดปุ่ม **"อัปโหลด USB"** เพื่อส่งคำสั่งชุดใหม่เข้าสู่บอร์ดผ่านสาย USB-UART (115200 baud) ได้ทันทีโดยไม่ต้องรอ Synthesis ใหม่!
"""
    with open(readme_path, "w", encoding="utf-8") as f:
        f.write(readme_content)

    return {
        "out_dir": out_dir,
        "top_v": top_path,
        "loader_v": loader_path,
        "xdc": xdc_path,
        "tcl": tcl_path,
        "program_hex": prog_hex_path,
        "copied_rtl": copied_rtl,
    }
